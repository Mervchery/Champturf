  select c.name, c.rating, t.id as trainer_id
  from csv c
  left join public.trainers t
    on t.normalized_name = public.normalize_name(
         case c.trainer when 'GUJADHUR' then 'Ramapatee Gujadhur'
                        when 'R GUJADHUR' then 'Rameshwar Gujadhur'
                        else c.trainer end)
)
insert into public.horses (name, rating, trainer_id)
select r.name, r.rating, r.trainer_id
from resolved r
where not exists (
  select 1 from public.horses h where public.normalize_name(h.name) = public.normalize_name(r.name)
);

